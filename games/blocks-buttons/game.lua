local direction_names = {up = "north", right = "west", down = "south", left = "west"}

local room_number, room, layout, tiles, buttons, crates
local player_x, player_y, direction, moving, complete, deadlocked
local moves, pushes, previous_actions, undo_state, card_ticks, campaign_complete

local function copy_points(values)
  local result = {}
  for index, value in ipairs(values) do result[index] = {x = value[1], y = value[2]} end
  return result
end

local function crate_at(x, y)
  for index, crate in ipairs(crates) do
    if crate.x == x and crate.y == y then return index end
  end
end

local function button_at(x, y)
  for _, button in ipairs(buttons) do
    if button.x == x and button.y == y then return true end
  end
  return false
end

local function wall_at(x, y)
  return x < 0 or y < 0 or x >= columns or y >= rows or
      layout[y + 1]:sub(x + 1, x + 1) == "#"
end

local function dead_square_at(x, y)
  for _, point in ipairs(room.d) do
    if point[1] == x and point[2] == y then return true end
  end
  return false
end

local function encode(point) return point.y * 8 + point.x end

local function save_room_state()
  sprout.storage_set("schema", 1)
  sprout.storage_set("room", room_number)
  sprout.storage_set("player-x", player_x)
  sprout.storage_set("player-y", player_y)
  sprout.storage_set("moves", moves)
  sprout.storage_set("pushes", pushes)
  sprout.storage_set("crate-count", #crates)
  for index = 1, 3 do sprout.storage_set("crate-" .. index, crates[index] and encode(crates[index]) or -1) end
end

local function build_tiles()
  tiles = ""
  for y = 1, rows do
    for x = 1, columns do tiles = tiles .. string.char(layout[y]:sub(x, x) == "#" and 1 or 0) end
  end
end

local function load_room(number, restore)
  room_number = math.max(1, math.min(#blocks_campaign, number))
  room = blocks_campaign[room_number]
  layout = room.w
  buttons = copy_points(room.b)
  crates = copy_points(room.c)
  player_x, player_y = room.p[1], room.p[2]
  direction, moving, complete, deadlocked = "down", nil, false, false
  campaign_complete, card_ticks, undo_state = false, 0, nil
  moves, pushes, previous_actions = 0, 0, {}
  build_tiles()
  if restore and sprout.storage_get("schema", 0) == 1 and
      sprout.storage_get("room", 0) == room_number then
    local count = sprout.storage_get("crate-count", 0)
    if count == #crates then
      local restored = {}
      for index = 1, count do
        local value = sprout.storage_get("crate-" .. index, -1)
        if value < 0 then restored = nil break end
        restored[index] = {x = value % 8, y = math.floor(value / 8)}
      end
      if restored then
        crates = restored
        player_x = sprout.storage_get("player-x", player_x)
        player_y = sprout.storage_get("player-y", player_y)
        moves = sprout.storage_get("moves", 0)
        pushes = sprout.storage_get("pushes", 0)
      end
    end
  end
end

local function remember_undo()
  undo_state = {player_x = player_x, player_y = player_y, crates = copy_points(
      (function() local values = {} for i,c in ipairs(crates) do values[i]={c.x,c.y} end return values end)()),
      moves = moves, pushes = pushes}
end

local function undo()
  if not undo_state or moving or complete or deadlocked then return end
  player_x, player_y = undo_state.player_x, undo_state.player_y
  crates, moves, pushes = undo_state.crates, undo_state.moves, undo_state.pushes
  undo_state = nil
  sprout.sfx("undo", 0.75)
  save_room_state()
end

local function evaluate()
  for _, button in ipairs(buttons) do
    if not crate_at(button.x, button.y) then
      for _, crate in ipairs(crates) do
        if not button_at(crate.x, crate.y) and dead_square_at(crate.x, crate.y) then
          deadlocked, card_ticks = true, 0
          sprout.sfx("fail")
          return
        end
      end
      save_room_state()
      return
    end
  end
  complete, card_ticks = true, 0
  sprout.sfx("win")
  sprout.emit("LevelCompleted", string.format("blocks-%03d", room_number))
  sprout.storage_set("completed-room", room_number)
end

function init()
  local selected = sprout.storage_get("schema", 0) == 1 and sprout.storage_get("room", 1) or 1
  load_room(selected, true)
end

function title_status() return "Room " .. room_number .. " / 30" end

function reset_progress()
  for _, key in ipairs({"schema","room","player-x","player-y","moves","pushes","crate-count","crate-1","crate-2","crate-3","completed-room"}) do
    sprout.storage_set(key, key == "room" and 1 or 0)
  end
  sprout.sfx("reset")
  load_room(1, false)
  save_room_state()
end

function update(actions)
  card_ticks = card_ticks + ((complete or deadlocked) and 1 or 0)
  if complete then
    if card_ticks >= card_duration or (actions.primary and not previous_actions.primary) then
      if room_number == #blocks_campaign then
        campaign_complete = true
      else
        load_room(room_number + 1, false)
        save_room_state()
      end
    end
    previous_actions = actions
    return
  end
  if deadlocked then
    if actions.primary and not previous_actions.primary then load_room(room_number, false); save_room_state() end
    previous_actions = actions
    return
  end
  if campaign_complete then previous_actions = actions return end
  if moving then
    moving.tick = moving.tick + 1
    if moving.tick >= move_duration then moving = nil; evaluate() end
    previous_actions = actions
    return
  end
  if actions.primary and not previous_actions.primary then undo(); previous_actions = actions return end
  local dx, dy = 0, 0
  if actions.up and not previous_actions.up then dy, direction = -1, "up"
  elseif actions.down and not previous_actions.down then dy, direction = 1, "down"
  elseif actions.left and not previous_actions.left then dx, direction = -1, "left"
  elseif actions.right and not previous_actions.right then dx, direction = 1, "right" end
  if dx ~= 0 or dy ~= 0 then
    local target_x, target_y = player_x + dx, player_y + dy
    local crate_index = crate_at(target_x, target_y)
    if not wall_at(target_x, target_y) then
      if crate_index then
        local crate_x, crate_y = target_x + dx, target_y + dy
        if wall_at(crate_x, crate_y) or crate_at(crate_x, crate_y) then
          sprout.sfx("blocked", 0.65)
        else
          remember_undo()
          moving = {tick=0, from_x=player_x, from_y=player_y, crate=crate_index,
                    crate_from_x=target_x, crate_from_y=target_y, pushing=true}
          crates[crate_index].x, crates[crate_index].y = crate_x, crate_y
          player_x, player_y, moves, pushes = target_x, target_y, moves + 1, pushes + 1
          sprout.sfx(button_at(crate_x, crate_y) and "button" or "push")
        end
      else
        remember_undo()
        moving = {tick=0, from_x=player_x, from_y=player_y, pushing=false}
        player_x, player_y, moves = target_x, target_y, moves + 1
      end
    else sprout.sfx("blocked", 0.45) end
  end
  previous_actions = actions
end

local function draw_card(kind)
  sprout.rect(0, 0, screen_width, screen_height, 12, 47, 91, 175)
  local age = math.min(1, card_ticks / 14)
  local wobble = math.sin(card_ticks / 8) * 4
  local width, height = math.floor(350 * age), math.floor(250 * age)
  local x, y = math.floor((screen_width - width) / 2), math.floor((screen_height - height) / 2 + wobble)
  if width < 40 then return end
  local fill = kind == "fail" and {143,44,54} or {246,240,223}
  sprout.rounded_rect(x, y, width, height, 28, fill[1], fill[2], fill[3], 248)
  if kind == "win" or kind == "campaign" then
    sprout.sprite("rich.crate-solved", screen_width/2, y+108, 0.38*age)
    sprout.display_label(kind == "campaign" and "Workshop complete!" or "All pressed!", x+24, y+142, width-48, 52, 16,47,91)
    sprout.label(kind == "campaign" and "A fresh campaign awaits" or "Next room coming up", x+30, y+198, width-60, 26, 112,67,39)
  else
    sprout.display_label("Crate stuck", x+24, y+60, width-48, 60, 246,240,223)
    sprout.label("A Retry    B Home", x+30, y+150, width-60, 34, 246,240,223)
  end
end

function render()
  sprout.rect(0, 0, screen_width, screen_height, 16, 47, 91)
  sprout.rect(0, 0, arena_x, screen_height, 23, 59, 112)
  sprout.rect(arena_x + cell*columns, 0, arena_x, screen_height, 23, 59, 112)
  for y=18,screen_height-20,54 do
    sprout.circle(40, y, 7, 57,175,204,110)
    sprout.circle(screen_width-40, y+18, 5, 255,197,59,110)
  end
  sprout.tilemap("room.tiles", tiles, columns, arena_x, arena_y, cell/16, cell/16)
  local sprites = {}
  for _, button in ipairs(buttons) do
    sprites[#sprites+1] = {sprite=crate_at(button.x,button.y) and "rich.button-down" or "rich.button-up",
      x=arena_x+button.x*cell+half_cell,y=arena_y+(button.y+1)*cell,scale=object_scale}
  end
  local progress = moving and math.min(1,moving.tick/move_duration) or 1
  local render_crates = {}
  for index,crate in ipairs(crates) do
    local x,y=crate.x,crate.y
    if moving and moving.crate==index then x=moving.crate_from_x+(crate.x-moving.crate_from_x)*progress; y=moving.crate_from_y+(crate.y-moving.crate_from_y)*progress end
    render_crates[#render_crates+1]={index=index,x=x,y=y}
  end
  local rx,ry=player_x,player_y
  if moving then rx=moving.from_x+(player_x-moving.from_x)*progress; ry=moving.from_y+(player_y-moving.from_y)*progress end
  for row=0,rows-1 do
    for _,entry in ipairs(render_crates) do if entry.y>=row and entry.y<row+1 then
      local crate=crates[entry.index]
      sprites[#sprites+1]={sprite=button_at(crate.x,crate.y) and "rich.crate-solved" or "rich.crate-idle",
        x=arena_x+entry.x*cell+half_cell,y=arena_y+(entry.y+1)*cell,scale=object_scale}
    end end
    if ry>=row and ry<row+1 then
      local facing=direction_names[direction]
      local id="rich.hero-"..facing.."-02"
      if moving then id=moving.pushing and "rich.hero-"..facing.."-push" or string.format("rich.hero-%s-%02d",facing,math.min(4,math.floor(progress*4)+1)) end
      sprites[#sprites+1]={sprite=id,x=arena_x+rx*cell+half_cell,y=arena_y+(ry+1)*cell,scale=robot_scale,flipX=direction=="right"}
    end
  end
  sprout.sprite_batch(sprites)
  sprout.rounded_rect(8,8,64,42,12,16,47,91,235)
  sprout.display_label(tostring(room_number),14,12,52,32,246,240,223)
  if campaign_complete then draw_card("campaign") elseif complete then draw_card("win") elseif deadlocked then draw_card("fail") end
end

function capture_scenario(name)
  if name == "gameplay" then load_room(10,false)
  elseif name == "win" then load_room(1,false); crates=copy_points(room.b); complete=true; card_ticks=18
  elseif name == "fail" then load_room(12,false); deadlocked=true; card_ticks=18
  elseif name == "undo" then load_room(4,false); undo_state={player_x=player_x,player_y=player_y,crates=copy_points(room.c),moves=0,pushes=0}
  elseif name == "late-gameplay" then load_room(29,false)
  else error("unsupported capture scenario: "..name) end
end

function snapshot()
  local values={room_number,player_x,player_y,direction,moves,pushes,complete and 1 or 0,deadlocked and 1 or 0}
  for _,crate in ipairs(crates) do values[#values+1]=crate.x; values[#values+1]=crate.y end
  return table.concat(values,":")
end
