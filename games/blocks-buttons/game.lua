local screen_width, screen_height = sprout.surface_size()
local columns, rows, cell = 8, 8, math.floor(screen_height / 8)
local arena_x = math.floor((screen_width - cell * columns) / 2)
local arena_y = 0
local half_cell = math.floor(cell / 2)
